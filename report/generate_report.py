"""Generate report/analysis_report.md.

The report:
  * runs each defense's self-test and renders an attack-vs-defense matrix
    showing which defense stops the attack and at which stage;
  * documents real-world supply-chain incidents and ties them to the mechanics
    demonstrated here;
  * covers responsible disclosure and the ethical boundaries of this research;
  * maps the defenses onto SLSA and the NIST SSDF.
"""
from __future__ import annotations

from pathlib import Path

# The five attack stages, in order. A defense "covers" the earliest stage at
# which it stops the attack.
STAGES = ["publish", "resolution", "download", "build/install", "runtime/import"]

# Static knowledge of where each defense acts (used when a live test can't run,
# and to place defenses on the stage axis).
DEFENSE_STAGE = {
    "namespace_reservation": "publish",
    "policy_scanner": "resolution",      # catches the config pre-install
    "scoped_registry": "resolution",
    "lockfile_pinning": "build/install",
    "signing_verification": "build/install",
}

DEFENSE_LABEL = {
    "lockfile_pinning": "Lockfile + hash pinning",
    "namespace_reservation": "Namespace reservation",
    "scoped_registry": "Scoped registry config",
    "signing_verification": "Signature verification",
    "policy_scanner": "Policy-as-code scan",
}


def _live_results() -> dict:
    """Try to run the defenses against the built impostor. Degrade gracefully."""
    results = {}
    try:
        from defenses import (lockfile_pinning, namespace_reservation,
                              scoped_registry, signing_verification, policy_scanner)
        for mod in (lockfile_pinning, namespace_reservation, scoped_registry,
                    signing_verification, policy_scanner):
            try:
                r = mod.test_against_attack()
                results[r["defense"]] = r
            except Exception as e:  # pragma: no cover
                results[mod.__name__.split(".")[-1]] = {"blocked": None,
                                                         "detail": f"error: {e}"}
    except Exception:
        pass
    return results


def _matrix(results: dict) -> str:
    header = "| Defense | Acts at stage | Blocks the attack? | How |\n"
    header += "|---|---|---|---|\n"
    rows = []
    for key in ("namespace_reservation", "policy_scanner", "scoped_registry",
                "lockfile_pinning", "signing_verification"):
        r = results.get(key, {})
        blocked = r.get("blocked")
        mark = {True: "✅ yes", False: "⚠️ no", None: "— (build first)"}[blocked]
        detail = r.get("detail", "")
        rows.append(f"| {DEFENSE_LABEL[key]} | {DEFENSE_STAGE[key]} | {mark} | {detail} |")
    return header + "\n".join(rows)


def _stage_grid(results: dict) -> str:
    """ASCII grid: defenses (rows) x stages (cols), ✓ where the defense stops it."""
    cols = STAGES
    head = "| Defense \\ Stage | " + " | ".join(cols) + " |\n"
    head += "|" + "---|" * (len(cols) + 1) + "\n"
    lines = []
    order = ["namespace_reservation", "scoped_registry", "policy_scanner",
             "lockfile_pinning", "signing_verification"]
    for key in order:
        stage = DEFENSE_STAGE[key]
        blocked = results.get(key, {}).get("blocked")
        cells = []
        reached = False
        for c in cols:
            if c == stage and blocked is not False:
                cells.append("🛑")  # stops here
                reached = True
            elif not reached:
                cells.append("·")   # attack still proceeding
            else:
                cells.append(" ")   # already stopped
        lines.append(f"| {DEFENSE_LABEL[key]} | " + " | ".join(cells) + " |")
    return head + "\n".join(lines)


BODY = """\
# Supply Chain Attack Simulator — Analysis Report

> Auto-generated by `report/generate_report.py`. Educational, local-only lab.

## 1. The attack, in one paragraph

Dependency confusion abuses how package managers resolve a name across multiple
indexes. When a resolver is configured to consider several indexes and pick the
**highest version** (pip's historical default; uv's `unsafe-best-match`), an
attacker who publishes a **higher version under an internal name** on any index
the resolver trusts gets that artifact installed. Installation and import then
execute attacker-controlled code (post-install hooks, import side effects). In
2021 Alex Birsan used exactly this to land code inside Apple, Microsoft, PayPal
and dozens of others, earning more than US$130,000 in bounties. No one typed a
malicious name; a permissive index configuration was enough.

## 2. Attack vs. defense matrix

Each defense was tested against the impostor produced by this lab.

{matrix}

### Stage grid (where each defense stops the attack)

The attack flows left to right: `publish → resolution → download → build/install
→ runtime/import`. 🛑 marks the earliest stage a defense halts it; `·` is the
attack still in progress.

{grid}

**Reading the grid.** Defenses that act *earlier* are strictly better: namespace
reservation and scoped registries prevent the impostor from ever being selected,
so no untrusted code is built at all. Lockfile hashing and signature
verification act later (at build/install) but are decisive — they refuse the
bytes. Policy-as-code acts earliest of all in practice, because it fails CI on
the *configuration* before a single install runs. Defense in depth means
combining an early preventive control with a late verifying control.

## 3. Real-world incidents

These are not all dependency confusion, but each illuminates a facet of the same
problem — trusting code you did not write and did not pin.

- **event-stream (npm, 2018).** A popular package's maintainer handed control to
  a volunteer who added a malicious transitive dependency (`flatmap-stream`) that
  targeted a specific Bitcoin wallet app and tried to steal keys. *Lesson:*
  maintainer-trust transfer and transitive deps are an attack surface; pinning
  and review of dependency changes matter. Relates to our **lockfile pinning**
  and **policy** defenses.

- **ua-parser-js (npm, 2021).** The maintainer's npm account was compromised and
  trojanized versions were published that ran a crypto-miner and a credential
  stealer via a **post-install script**. *Lesson:* install-time scripts execute
  arbitrary code — exactly the mechanism our demo package uses. Relates to our
  **signature verification** and **network/filesystem detection**.

- **colors.js / faker.js (npm, 2022).** The maintainer intentionally shipped an
  infinite-loop / garbage-output update ("protestware"), breaking thousands of
  builds. *Lesson:* even without an external attacker, unpinned "latest"
  dependencies are a availability and integrity risk. Relates to **lockfile
  pinning** (reproducible, pinned builds don't float to a sabotaged version).

Common root cause across all three and dependency confusion: **implicit trust in
the latest published version of a name, plus code execution at install time.**

## 4. Frameworks: SLSA and SSDF

- **SLSA (Supply-chain Levels for Software Artifacts).** The defenses here climb
  the SLSA ladder: signed artifacts + provenance (our **signature verification**)
  and reproducible, pinned builds (our **lockfile pinning**) are core SLSA
  requirements. Scoped, authenticated registries support SLSA's "trusted source"
  expectations.
- **NIST SSDF (SP 800-218).** Maps to practices **PW.4** (reuse only
  well-secured components — namespace reservation, scoped registries), **PS.2 /
  PS.3** (protect and verify software integrity — signing, hashes), and **PO.3**
  (toolchain security — policy-as-code in CI, egress control for builds).

## 5. Detection recap

- **Hash/lockfile check** — deterministic; refuses any artifact whose
  version/hash isn't pinned. Best signal, no behavior needed.
- **Network monitor** — flags install-time egress to anything but your index.
  Catches the "phone home" even for a zero-day name you hadn't pinned.
- **Filesystem monitor** — flags install-time code touching credential-like
  paths. Catches the *intent* (staging secrets) rather than the delivery.

Layer them: the hash check stops known-shape swaps; network/filesystem
monitoring catch novel payloads that slip a pin you forgot.

## 6. Responsible disclosure and ethical boundaries

This project is a **defensive** teaching tool. The boundaries it respects, and
that any supply-chain researcher must respect:

1. **Never publish to a public registry.** Birsan's research was authorized and
   coordinated; uploading a name-squat or a high-version impostor to real PyPI/
   npm to "prove a point" is unauthorized access and can break real builds. This
   lab is hard-wired to localhost and ships a `Private :: Do Not Upload`
   classifier as a second guard.
2. **Collect nothing sensitive, exfiltrate nowhere real.** The demo payload
   gathers only non-identifying metadata and sends it to `127.0.0.1`. It never
   reads secrets, keys, or the app's own `.env`. That line — between
   demonstrating a mechanism and actually stealing data — is the line between
   research and crime.
3. **Test only systems you own or are authorized to test.** Dependency
   confusion against a third party without written authorization is illegal in
   most jurisdictions (e.g., CFAA in the US) regardless of intent.
4. **Disclose coordinately.** If you discover a real exposure (an internal name
   unclaimed on a public index), report it privately to the affected
   organization and the registry, give reasonable time to remediate (reserve the
   name, fix the config), and avoid publishing exploit details until fixed.
5. **Minimize blast radius.** Proof-of-concepts should be inert: no persistence,
   no spreading, no real data, clear labeling as a test.

If you adapt this lab for training, keep every one of these properties. Do not
reuse the metadata-collection snippet in any package you distribute.

## 7. Try it yourself

```bash
python -m scsim.runner run --narrated          # full guided demo
python -m defenses.policy_scanner target-app/pyproject.toml   # CI gate on the vuln config
```
"""


def generate() -> Path:
    from scsim.config import REPORT_DIR
    results = _live_results()
    text = BODY.format(matrix=_matrix(results), grid=_stage_grid(results))
    out = REPORT_DIR / "analysis_report.md"
    out.write_text(text, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(generate())
